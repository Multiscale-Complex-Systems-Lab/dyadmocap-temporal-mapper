function fig = plotCorrStarKey()
%PLOTCORRSTARKEY  The key to the correlation bar figures, as its own figure.
%
%   fig = plotCorrStarKey();
%
% The result figures carry no legend; keys are saved once as their own figure,
% like ConditionLegend. This one explains the two kinds of star in
% plotCorrPairBars:
%   star ON a bar      = that state's rho differs from 0
%   star ON a bracket  = the two states' rho differ from each other
%
% Written by Patience Akatuhwera with help from Claude (Anthropic, an AI
% assistant). The author reviewed the code and is responsible for it.

lines = { ...
    '\bf Key', ...
    '', ...
    'Bar: Spearman \rho between Casual Chat and Conflict, over dyads', ...
    'Error bar: 95% CI (BCa bootstrap, 10,000 dyad resamples)', ...
    '', ...
    '* on a bar: \rho differs from 0', ...
    'No star on a bar: \rho does not differ from 0 (not significant)', ...
    '* on a bracket: the two states differ in consistency', ...
    '', ...
    '*  p < .05      **  p < .01      ***  p < .001', ...
    'Pairs that do not differ are not shown (6 pairs, uncorrected)'};

fig = figure('Units','inches', 'Position',[1 1 13 10], 'Color','w');
ax  = axes(fig, 'Position',[0 0 1 1], 'Visible','off');
text(ax, 0.05, 0.5, lines, 'Units','normalized', 'FontSize',26, ...
     'FontWeight','bold', 'Interpreter','tex', 'VerticalAlignment','middle');
end
